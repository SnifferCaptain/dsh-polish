// Builds `lib/client.mermaid.js` — the package-local dynamic chunk the
// visualize engine loads on demand (DSH client-modules chunk protocol: the
// file must be named client.<x>.js, it ships as a classic script, and it
// registers itself through window.__ModuleLoader__.load with the id
// "<owner>/<fileName>").
//
// The registered factory follows the loader's materialization convention:
// the loader calls factory(require) and uses the RETURN VALUE as the module
// exports (no exports/module injection), so the factory creates its own
// module object and returns it — same shape as every shipped DSH chunk.
//
// The file lives NEXT TO the client entry (lib/client.js): the Host resolves
// a `require.async('./client.<x>.js')` request against the directory of the
// package's `./client` export (dsh-client-modules: join(dirname(clientPath),
// fileName)), so a chunk at the package root is never found (404) and every
// mermaid fence dies in the "chunk load failed" error path.
//
// The vendored artifact is the official esbuild IIFE build of mermaid
// 11.17.0 (the same release dsh-mermaid pins); executing it sets
// globalThis.mermaid, which the wrapper then hands to the module system.
//
//   node scripts/build-mermaid-chunk.cjs          # write client.mermaid.js
//   node scripts/build-mermaid-chunk.cjs --check  # verify the committed chunk
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const vendorFile = path.join(root, 'vendor', 'mermaid-11.17.0.min.js')
// The chunk must sit beside the client entry (lib/client.js) so the Host's
// dirname(clientPath) resolution finds it. See the header note.
const outputPath = path.join(root, 'lib', 'client.mermaid.js')
const VERSION = '11.17.0'
const MARKER = 'dsh-polish mermaid chunk v' + VERSION
const checkOnly = process.argv.includes('--check')
const unknownArgs = process.argv.slice(2).filter((arg) => arg !== '--check')
if (unknownArgs.length > 0) throw new Error('unknown argument: ' + unknownArgs.join(' '))

function build() {
  const mermaid = fs.readFileSync(vendorFile, 'utf8')
  const header =
    '// ' + MARKER + '\n' +
    '// Auto-generated by scripts/build-mermaid-chunk.cjs — do not edit by hand.\n' +
    '//\n' +
    '// mermaid ' + VERSION + ' (MIT) official dist/mermaid.min.js, inlined verbatim so the\n' +
    '// visualize engine can load it as a DSH client-modules package-local chunk\n' +
    '// without any CDN. The vendored build is a classic-script IIFE: its top-level\n' +
    '// `var __esbuild_esm_mermaid_nm` must reach the global scope (it is read back\n' +
    '// via `globalThis.__esbuild_esm_mermaid_nm` on the final line), so it is NOT\n' +
    '// wrapped in a function. After it runs, globalThis.mermaid is the API; the\n' +
    '// trailing IIFE only registers it with the client module loader.\n'
  const body =
    mermaid +
    '\n;(function () {\n' +
    "  'use strict'\n" +
    '  var api = (typeof globalThis !== "undefined" ? globalThis : this).mermaid\n' +
    '  if (!api) throw new Error("dsh-polish: mermaid ' + VERSION + ' did not expose globalThis.mermaid")\n' +
    '  if (typeof window === "undefined" || !window.__ModuleLoader__) {\n' +
    '    // Outside the DSH client (e.g. a bare browser tab): keep the global only.\n' +
    '    return\n' +
    '  }\n' +
    '  window.__ModuleLoader__.load({\n' +
    "    id: 'dsh-polish/client.mermaid.js',\n" +
    '    // The loader materializes a factory by calling factory(require) and\n' +
    '    // USING ITS RETURN VALUE as the module exports (dsh-client-modules).\n' +
    '    // So, like every shipped DSH chunk, create the module here and return\n' +
    '    // it — do not rely on (require, exports, module) being injected.\n' +
    '    factory: function (require) {\n' +
    '      var module = { exports: {} }\n' +
    '      module.exports = api\n' +
    '      module.exports.default = api\n' +
    '      return module.exports\n' +
    '    },\n' +
    '  })\n' +
    '})()\n'
  return header + body
}

if (checkOnly) {
  if (!fs.existsSync(outputPath)) {
    console.error('client.mermaid.js is missing — run: node scripts/build-mermaid-chunk.cjs')
    process.exitCode = 1
  } else {
    const current = fs.readFileSync(outputPath, 'utf8')
    const expected = build()
    if (current !== expected) {
      console.error('client.mermaid.js is out of date — run: node scripts/build-mermaid-chunk.cjs')
      process.exitCode = 1
    } else {
      console.log('client.mermaid.js matches vendor/mermaid-' + VERSION + '.min.js (' + current.length + ' bytes)')
    }
  }
} else {
  fs.writeFileSync(outputPath, build())
  console.log('built client.mermaid.js (' + fs.statSync(outputPath).size + ' bytes, mermaid ' + VERSION + ')')
}
