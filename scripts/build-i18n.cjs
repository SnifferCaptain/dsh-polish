// Generates src/client/shared/i18n.js from locale/zh.jsonc + locale/en.jsonc.
//
// The JSONC files are the source of truth for user-visible copy (language =
// file name); this script strips // and /* */ comments (never inside strings)
// and emits a single JS literal that the browser entry concatenates. Run via
// `node scripts/build-i18n.cjs`; `--check` exits non-zero when the generated
// file would differ, without writing.
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const sources = { en: path.join(root, 'locale', 'en.jsonc'), zh: path.join(root, 'locale', 'zh.jsonc') }
const output = path.join(root, 'src', 'client', 'shared', 'i18n.js')
const checkOnly = process.argv.includes('--check')
const unknown = process.argv.slice(2).filter((a) => a !== '--check')
if (unknown.length > 0) throw new Error('unknown argument: ' + unknown.join(' '))

/** Strip // line comments and /* *\/ block comments from JSONC, string-aware. */
function stripJsoncComments(text) {
  let out = ''
  let i = 0
  let inString = false
  while (i < text.length) {
    const c = text[i]
    const n = text[i + 1]
    if (inString) {
      out += c
      if (c === '\\') {
        out += n === undefined ? '' : n
        i += 2
        continue
      }
      if (c === '"') inString = false
      i += 1
      continue
    }
    if (c === '"') {
      inString = true
      out += c
      i += 1
      continue
    }
    if (c === '/' && n === '/') {
      while (i < text.length && text[i] !== '\n') i += 1
      continue
    }
    if (c === '/' && n === '*') {
      i += 2
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i += 1
      i += 2
      continue
    }
    out += c
    i += 1
  }
  return out
}

function flatKeys(object, prefix, keys) {
  for (const group of Object.keys(object)) {
    const full = prefix ? prefix + '.' + group : group
    for (const leaf of Object.keys(object[group])) {
      const value = object[group][leaf]
      if (value && typeof value === 'object') flatKeys(value, full, keys)
      else keys[full + '.' + leaf] = value
    }
  }
  return keys
}

function flatten(obj) {
  return flatKeys(obj, '', {})
}

function emitEntry(key, value) {
  return "        " + JSON.stringify(key) + ": " + JSON.stringify(value) + ","
}

function groupKeys(flat) {
  // group by first segment, preserving first-seen order
  const groups = []
  const index = {}
  for (const key of Object.keys(flat)) {
    const group = key.split('.')[0]
    if (!index[group]) {
      index[group] = { group: group, lines: [] }
      groups.push(index[group])
    }
    index[group].lines.push(emitEntry(key, flat[key]))
  }
  return groups
}

function emitSection(lang, flat) {
  const lines = []
  lines.push('      ' + lang + ': {')
  for (const g of groupKeys(flat)) {
    lines.push("        // --- " + g.group)
    lines.push(...g.lines)
  }
  lines.push('      },')
  return lines
}

function build(enText, zhText) {
  const en = flatten(JSON.parse(stripJsoncComments(enText)))
  const zh = flatten(JSON.parse(stripJsoncComments(zhText)))
  const missingInEn = Object.keys(zh).filter((k) => en[k] === undefined)
  const missingInZh = Object.keys(en).filter((k) => zh[k] === undefined)
  if (missingInEn.length > 0) throw new Error('keys missing in en.jsonc: ' + missingInEn.join(', '))
  if (missingInZh.length > 0) throw new Error('keys missing in zh.jsonc: ' + missingInZh.join(', '))

  const header = [
    "    // ------------------------------------------------------- i18n (shared)",
    "    //",
    "    // GENERATED by scripts/build-i18n.cjs from locale/zh.jsonc + locale/en.jsonc.",
    "    // Do not edit this file by hand; edit the locale/*.jsonc sources and",
    "    // re-run the build. The language is the file name; a missing entry in",
    "    // the active language falls back to zh, then to the key itself.",
    "    //",
    "    // t(key, ...args): {name} placeholders are substituted from a single",
    "    // object argument (t('key', {n: 3})); {n} also takes the positional",
    "    // argument at index n. The active language follows the DSH client",
    "    // locale service (ctx.locale, injected on the bundle) — dshI18nBind()",
    "    // is called once from apply() and re-reads the snapshot on every",
    "    // locale change, so slot-rendered copy switches live.",
    "",
    "    var DSHI18N_DICT = {",
  ]
  const footer = [
    "    }",
    "",
    "    var dshI18nLang = null",
    "    var dshI18nDict = {}",
    "    var dshI18nRevision = 0",
    "",
    "    function dshI18nBind(ctx) {",
    "      var locale = ctx && ctx.locale",
    "      if (!locale || typeof locale.getSnapshot !== 'function') return",
    "      try {",
    "        dshI18nApplySnapshot(locale.getSnapshot())",
    "      } catch (error) {",
    "        return",
    "      }",
    "      try {",
    "        locale.subscribe(function () {",
    "          try {",
    "            dshI18nApplySnapshot(locale.getSnapshot())",
    "          } catch (error) { /* keep the last good language */ }",
    "        })",
    "      } catch (error) { /* snapshot-only mode */ }",
    "    }",
    "",
    "    // The generated module must not expose the bind helper to call sites: the",
    "    // apply() entry is the single place that may bind the locale service.",
    "    globalThis.dshI18nBind = dshI18nBind",
    "    function dshI18nPrimaryOf(id) {",
    "      return String(id).split(/[-_]/)[0].toLowerCase()",
    "    }",
    "",
    "    function dshI18nApplySnapshot(snapshot) {",
    "      // LocaleSnapshot carries the active language id under a property that",
    "      // varies by DSH version: `locale`, `language`, `id`, or `lang`. A bare",
    "      // non-empty string snapshot is treated as the id itself.",
    "      var id = null",
    "      if (typeof snapshot === 'string' && snapshot.trim() !== '') {",
    "        id = snapshot",
    "      } else if (snapshot && typeof snapshot === 'object') {",
    "        var candidates = ['locale', 'language', 'id', 'lang']",
    "        for (var i = 0; i < candidates.length; i++) {",
    "          var v = snapshot[candidates[i]]",
    "          if (typeof v === 'string' && v.trim() !== '') {",
    "            id = v",
    "            break",
    "          }",
    "        }",
    "      }",
    "      if (id === null || DSHI18N_DICT[dshI18nPrimaryOf(id)] === undefined) id = 'zh'",
    "      id = dshI18nPrimaryOf(id)",
    "      if (id === dshI18nLang && dshI18nDict.length !== 0) return",
    "      dshI18nLang = id",
    "      dshI18nDict = DSHI18N_DICT[id]",
    "      dshI18nRevision += 1",
    "    }",
    "",
    "    /**",
    "     * Translate a key for the active DSH UI language. {name} placeholders are",
    "     * substituted from a single object argument (t('key', {n: 3})) or, for {n},",
    "     * from the positional argument at index n. Fallback chain: active language",
    "     * → zh → the key itself.",
    "     */",
    "    function t(key) {",
    "      var value = dshI18nDict && dshI18nDict[key] !== undefined ? dshI18nDict[key] : DSHI18N_DICT.zh[key]",
    "      if (value === undefined) return key",
    "      var rest = Array.prototype.slice.call(arguments, 1)",
    "      var named = rest.length === 1 && typeof rest[0] === 'object' && rest[0] !== null",
    "        ? rest[0]",
    "        : null",
    "      return String(value).replace(/\\{(\\w+)\\}/g, function (whole, name) {",
    "        if (named && name in named) return String(named[name])",
    "        if (name === 'n') {",
    "          var index = Number(whole.slice(1, -1))",
    "          return rest[index] !== undefined ? String(rest[index]) : whole",
    "        }",
    "        return whole",
    "      })",
    "    }",
    "",
    "    function dshI18nForceLang(lang) {",
    "      if (DSHI18N_DICT[dshI18nPrimaryOf(lang)] === undefined) lang = 'zh'",
    "      dshI18nLang = dshI18nPrimaryOf(lang)",
    "      dshI18nDict = DSHI18N_DICT[dshI18nLang]",
    "      dshI18nRevision += 1",
    "    }",
    "",
  ]
  const body = [].concat(
    header,
    emitSection('en', en),
    emitSection('zh', zh),
    footer,
  )
  return body.join('\n')
}

const enText = fs.readFileSync(sources.en, 'utf8')
const zhText = fs.readFileSync(sources.zh, 'utf8')
const generated = build(enText, zhText)

if (checkOnly) {
  const current = fs.readFileSync(output, 'utf8')
  if (current !== generated) {
    console.error('src/client/shared/i18n.js is out of date; run: node scripts/build-i18n.cjs')
    process.exitCode = 1
  } else {
    console.log('src/client/shared/i18n.js matches locale/ (' + generated.length + ' chars)')
  }
} else {
  fs.writeFileSync(output, generated)
  console.log('built src/client/shared/i18n.js (' + generated.length + ' chars)')
}
